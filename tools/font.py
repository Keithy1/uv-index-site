"""Compile the site's typeface into src/assets/font.ts. Run once after changing it:

    python tools/font.py

Atkinson Hyperlegible Next, SIL Open Font License 1.1 (tools/atkinson-hyperlegible-next-OFL.txt;
see docs/licences.md). The WOFF2 is Google Fonts' Latin subset of the variable font,
v7, fetched 30 October 2026 from the css2 API: one 34 KB file carries every weight
from 200 to 800, so 400, 700 and 800 cost one request rather than three. The licence
names no Reserved Font Name, so a subset may keep the name.

Compiled in as base64, like the brand images, so the Worker serves it with no storage
to pay for. The licence is served beside it, because the OFL asks that it travel with
the font and Google's subset carries no licence text in its name table.
"""
import base64
import json

FONT = "tools/atkinson-hyperlegible-next-latin.woff2"
LICENCE = "tools/atkinson-hyperlegible-next-OFL.txt"
OUT = "src/assets/font.ts"


def main() -> None:
    font = base64.b64encode(open(FONT, "rb").read()).decode()
    licence = open(LICENCE, encoding="utf-8").read()
    lines = [font[i:i + 100] for i in range(0, len(font), 100)]
    body = " +\n  ".join(f'"{line}"' for line in lines)
    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write(
            "/**\n"
            " * Atkinson Hyperlegible Next, Latin, every weight in one variable WOFF2.\n"
            " * Generated by tools/font.py; edit that, not this.\n"
            " */\n"
            "const decode = (b64: string): Uint8Array => Uint8Array.from(atob(b64), (ch) => ch.charCodeAt(0));\n\n"
            "/** Versioned, so the year-long immutable cache can never serve an old face. */\n"
            'export const FONT_PATH = "/atkinson-hyperlegible-next-v7.woff2";\n'
            f"export const FONT_BYTES = decode(\n  {body},\n);\n\n"
            'export const FONT_LICENCE_PATH = "/atkinson-hyperlegible-next-OFL.txt";\n'
            f"export const FONT_LICENCE = {json.dumps(licence)};\n"
        )


if __name__ == "__main__":
    main()
