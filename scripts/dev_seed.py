"""Development only: load a real CAMS GRIB into the LOCAL D1 as today's forecast.

There is no forecast in the database yet -- nothing carries CAMS records into
D1 -- so a city page has no curve to draw and cannot be looked at. This fills
that gap for development without inventing numbers: it reads an actual CAMS
download and shifts its dates onto today, so the shapes and magnitudes are
real even though the day is not.

NEVER point this at the production database. It writes rows that claim to be
today's forecast and are not.

    python scripts/dev_seed.py <path-to.grib>
    npm run db:seed:local        # applies the SQL it writes

The GRIB can be pulled from any cams-probe workflow run:
    gh run download <id> -n cams-probe-download
"""
from __future__ import annotations

import sys
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from fetch.cams import parse_grib  # noqa: E402

OUT = Path("dev-seed.sql")


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print(__doc__)
        return 2
    grib = argv[1]

    records = parse_grib(grib)
    if not records:
        print("no records parsed", file=sys.stderr)
        return 1

    # Shift every record so the run's first day becomes today (UTC), then
    # repeat it for tomorrow. Two days are needed because a local day is never
    # a UTC day: at 6 am in Sydney, "today" there is already tomorrow in UTC.
    first_day = min(r.valid_at for r in records).date()
    shift = date.today() - first_day
    print(f"{len(records)} records, shifting {shift.days} day(s) onto today, x2 days")

    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "-- DEVELOPMENT SEED. Real CAMS values, shifted onto today's date.",
        "-- Generated by scripts/dev_seed.py. Never apply to production.",
        "DELETE FROM readings WHERE source = 'cams';",
    ]
    def insert(location: str, kind: str, valid: str, uvi: float, issued: str) -> str:
        return (
            "INSERT OR REPLACE INTO readings "
            "(location_id, source, kind, valid_at, uvi, issued_at, fetched_at) VALUES "
            f"('{location}', 'cams', '{kind}', '{valid}', {uvi}, {issued}, '{now}');"
        )

    for extra_day in (0, 1):
        offset = shift + timedelta(days=extra_day)
        for r in records:
            valid = (r.valid_at + offset).strftime("%Y-%m-%dT%H:%M:%SZ")
            issued = (
                f"'{(r.issued_at + offset).strftime('%Y-%m-%dT%H:%M:%SZ')}'"
                if r.issued_at
                else "NULL"
            )
            lines.append(insert(r.location, "forecast", valid, r.uvi, issued))
            clear = (r.extra or {}).get("clear_sky_uvi")
            if clear is not None:
                lines.append(insert(r.location, "forecast_clear", valid, clear, issued))

    OUT.write_text("\n".join(lines) + "\n", encoding="utf8")
    print(f"wrote {OUT} ({len(lines) - 3} inserts)")
    print("apply with: npm run db:seed:local")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
