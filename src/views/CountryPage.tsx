/** The views, in the order they appear on the switch. */
const VIEW_IDS = ["now", "peak", "tomorrow"] as const;
type ViewId = (typeof VIEW_IDS)[number];

/** Takes a cell's contents off screen and keeps them for a screen reader. */
const OFF_SCREEN =
  "{position:absolute;width:1px;height:1px;overflow:hidden;clip:rect(0 0 0 0);white-space:nowrap}";

/**
 * Show/hide rules for every view, generated rather than written out.
 *
 * Each view drives the map's marker groups, its caption, which value column
 * the list shows and which day its strips draw. Writing those by hand is how
 * the switch came to say "Today" above a map showing the current hour: the
 * label and the layer it controlled were maintained separately.
 *
 * A value column the view does not show is collapsed, not removed: its cells
 * keep their text off screen, so a screen reader reads every figure in every
 * row against its heading, whichever view is chosen.
 */
function switchRules(views: readonly ViewId[]): string {
  let css = "";
  for (const view of views) {
    const on = `#day-${view}:checked~`;
    css += `${on}.dayswitch label[for="day-${view}"]{background:var(--zenith);color:var(--sky)}`;
    // Focus must show on the label, since the radio itself is off-screen.
    css += `#day-${view}:focus-visible~.dayswitch label[for="day-${view}"]{outline:3px solid var(--zenith);outline-offset:-3px}`;
    for (const layer of views) {
      const show = layer === view ? "inline" : "none";
      css += `${on}.mapbox .m-${layer},${on}.daycap .m-${layer}{display:${show}}`;
      // Hover previews a view on the map without committing to it.
      css += `.daymap:has(label[for="day-${view}"]:hover) .mapbox .m-${layer}{display:${show}}`;
    }
    const others = views.filter((l) => l !== view);
    if (others.length) {
      css += `${others.map((l) => `${on}.list .k-${l}`).join(",")}{padding:0;width:0}`;
      css += `${others.map((l) => `${on}.list .k-${l}>*`).join(",")}${OFF_SCREEN}`;
    }
  }
  if (views.includes("tomorrow")) {
    css += `#day-tomorrow:checked~.list .s-today{display:none}#day-tomorrow:checked~.list .s-tomorrow{display:flex}`;
  }
  return css;
}

/**
 * Every city on the page, A to Z, each a link to its own page.
 *
 * The list is sorted by the level now, highest first -- the right order for
 * "where is it worst", and the wrong one for "how is Tucson": fifty US cities
 * in an order that changes every hour is a long scroll to find one. A
 * <details> like the header's Country menu, so it works with JavaScript off.
 * US cities carry their state, because Portland and Columbus are two places.
 */
function CityPicker({ rows }: { rows: readonly CityRow[] }) {
  const cities = rows
    .map((r) => r.location)
    .sort((a, b) => cityLabel(a).localeCompare(cityLabel(b)));
  return (
    <details class="citypick">
      <summary>Choose a city</summary>
      <ul>
        {cities.map((l) => (
          <li key={l.id}>
            <a href={`/${l.country}/${l.slug}/`}>{cityLabel(l)}</a>
          </li>
        ))}
      </ul>
    </details>
  );
}

/**
 * A value with its band swatch. The swatch is the band's colour only; the
 * number is what a screen reader reads, and what the band comes from.
 */
function Value({ uvi }: { uvi: number | null }) {
  if (uvi === null) return <span>—</span>;
  return <b class={`b${BANDS.indexOf(bandFor(uvi))}`}>{formatUvi(uvi)}</b>;
}

/**
 * The level now, with when it was measured where it was. A reading past the
 * staleness rule is shown as what it is: an old number, in grey, with no band,
 * and how old it is.
 */
function NowCell({ row, now, measured }: { row: CityRow; now: Date; measured: boolean }) {
  if (row.stale && row.uvi !== null && row.validAt) {
    return (
      <td class="k-now">
        <b class="old">{formatUvi(row.uvi)}</b>
        <small>{agoShort(row.validAt, now)}</small>
      </td>
    );
  }
  return (
    <td class="k-now">
      <Value uvi={row.uvi} />
      {measured && row.validAt && row.uvi !== null && <small>{localTime(row.validAt, row.location.tz)}</small>}
    </td>
  );
}

/** "6 am" on a wide screen, "6" on a phone, every third hour across the axis. */
function AxisLabels({ axis }: { axis: StripAxis }) {
  const labels = [];
  for (let m = Math.ceil(axis.from / 180) * 180; m <= axis.to; m += 180) {
    const at = (m - axis.from) / (axis.to - axis.from);
    // Not at the very ends, where half the label would hang outside the column.
    if (at < 0.04 || at > 0.96) continue;
    const h = (m / 60) % 24;
    labels.push(
      <i style={`left:${(at * 100).toFixed(1)}%`}>
        {((h + 11) % 12) + 1}
        <span class="ap">{h < 12 ? " am" : " pm"}</span>
      </i>,
    );
  }
  return <div class="ax" aria-hidden="true">{labels}</div>;
}

/**
 * A map coordinate to one decimal place.
 *
 * Projected coordinates came out to thirteen decimal places
 * (cx="440.7960170020942"), and with three views of fifty US cities the map
 * was 101 KB of a 141 KB page. A tenth of a map unit is far below a pixel.
 */
const r1 = (n: number): number => Math.round(n * 10) / 10;

/**
 * The markers, each a link to its city page where one exists.
 *
 * tabindex="-1": the same links are in the list and the city picker, where a
 * keyboard reaches them in a sensible order. Nor do the markers carry labels
 * of their own -- the <svg> is role="img", which makes everything inside it
 * presentational. The map's own label points to the list instead.
 */
function MarkerLayer({
  rows,
  map,
  value,
  old,
  linked,
}: {
  rows: readonly CityRow[];
  map: CountryMap;
  value: (r: CityRow) => number | null;
  /** Past the staleness rule: drawn grey, with no band, like its row. */
  old?: (r: CityRow) => boolean;
  linked: boolean;
}) {
  return (
    <>
      {rows.map((r) => {
        const uvi = value(r);
        if (uvi === null) return null;
        const p = map.project(r.location.lat, r.location.lon);
        const x = r1(p.x), y = r1(p.y);
        const band = bandFor(uvi);
        const grey = old?.(r) ?? false;
        const pin = (
          <g key={r.location.id} class={`pin p-${r.location.id}`}>
            <circle cx={x} cy={y} r="6" fill={grey ? "var(--horizon)" : band.bg} />
            <text x={x} y={r1(y + 3.2)} fill={grey ? "var(--haze)" : band.fg}>{Math.round(uvi)}</text>
          </g>
        );
        return linked ? (
          <a key={r.location.id} href={`/${r.location.country}/${r.location.slug}/`} tabindex={-1}>
            {pin}
          </a>
        ) : (
          pin
        );
      })}
    </>
  );
}

/**
 * Hover labels, drawn after every marker, and one per city rather than one
 * per view.
 *
 * After, because SVG paints in document order and has no working z-index: a
 * label beside its own marker is covered by the next marker along. One per
 * city, because the label is the city's name; the number is on the pin and in
 * the list. Three labels a city, each with its view's value, were 20 KB of /us/.
 */
function TipLayer({ rows, map }: { rows: readonly CityRow[]; map: CountryMap }) {
  return (
    <g aria-hidden="true">
      {rows.map((r) => {
        const p = map.project(r.location.lat, r.location.lon);
        const x = r1(p.x), y = r1(p.y);
        const label = r.location.name;
        // SVG cannot size a box to its text, so estimate from character
        // count: generous rather than tight, because too narrow clips.
        const width = r1(label.length * 4.6 + 12);
        const flip = y < 26; // near the top edge, put the label below instead
        const ty = flip ? y + 13 : y - 23;
        return (
          <g key={r.location.id} class={`tip t-${r.location.id}`}>
            <rect x={r1(x - width / 2)} y={r1(ty)} width={width} height="15" rx="4" />
            <text x={x} y={r1(ty + 10.5)}>{label}</text>
          </g>
        );
      })}
    </g>
  );
}

/** One rule per city, joining its marker to its label across the two layers. */
function tipRules(rows: readonly CityRow[]): string {
  return rows
    .map((r) => `.daymap:has(.p-${r.location.id}:hover) .t-${r.location.id}{opacity:1}`)
    .join("");
}

interface View {
  id: ViewId;
  label: string;
  caption: string;
  heading: string;
  value: (r: CityRow) => number | null;
  old?: (r: CityRow) => boolean;
}

/** A view only appears if there is data behind it. */
function viewsFor(rows: readonly CityRow[], measured: boolean): View[] {
  const views: View[] = [
    {
      id: "now",
      label: measured ? "Now" : "Now (forecast)",
      caption: measured
        ? "The map shows the level measured now."
        : "The map shows the forecast for the current hour; there is no measured UV source for the United States.",
      // The column heading is the credit for every figure under it.
      heading: measured ? "Measured by ARPANSA" : "Now, forecast",
      value: (r) => r.uvi,
      old: (r) => r.stale,
    },
  ];
  if (rows.some((r) => r.peak !== null)) {
    views.push({
      id: "peak",
      label: "Peak today",
      caption: "The map shows the highest level forecast for today, in each city's own day.",
      heading: "Peak today, forecast",
      value: (r) => r.peak,
    });
  }
  if (rows.some((r) => r.tomorrow !== null)) {
    views.push({
      id: "tomorrow",
      label: "Tomorrow",
      // "UV index tomorrow" said in so many words: it is searched for (over 1k a
      // month in the US) and this page is where it is answered.
      caption: "The map shows the UV index tomorrow: the highest level forecast in each city's own day.",
      heading: "Tomorrow, forecast peak",
      value: (r) => r.tomorrow,
    });
  }
  return views;
}

function CountryMapView({
  rows,
  views,
  map,
  countryName,
  cityPages,
}: {
  rows: readonly CityRow[];
  views: readonly View[];
  map: CountryMap;
  countryName: string;
  cityPages: boolean;
}) {
  return (
    <>
      <div class="mapbox">
        <svg
          viewBox={`0 0 ${map.width} ${map.height}`}
          role="img"
          aria-label={`Map of ${countryName} with a marker for each city. The same figures are in the list above.`}
        >
          <path d={map.outlinePath} fill="var(--horizon)" stroke="var(--haze)" stroke-width="0.8"
            stroke-linejoin="round" opacity="0.75" />
          {views.map((v) => (
            <g key={v.id} class={`m-${v.id}`}>
              <MarkerLayer rows={rows} map={map} value={v.value} old={v.old} linked={cityPages} />
            </g>
          ))}
          <TipLayer rows={rows} map={map} />
        </svg>
      </div>
      {views.length > 1 && (
        <p class="daycap">
          {/* Driven by the same generated rules as the markers, so the words
              and the map cannot disagree about what is shown. */}
          {views.map((v) => (
            <span key={v.id} class={`m-${v.id}`}>
              {v.caption}
            </span>
          ))}
        </p>
      )}
    </>
  );
}

/**
 * The list: one row per city, ranked by the level now.
 *
 * City, then a value column per view (the switch shows one), then the strip.
 * The strip column's heading carries its credit and the hour labels, drawn
 * once for every row against the axis they share; the heading sticks while
 * the fifty rows scroll under it.
 */
function CityList({
  rows,
  views,
  now,
  measured,
  cityPages,
  stripCredit,
}: {
  rows: readonly CityRow[];
  views: readonly View[];
  now: Date;
  measured: boolean;
  cityPages: boolean;
  stripCredit: string;
}) {
  const ids = new Set(views.map((v) => v.id));
  const axis = stripAxis(rows.flatMap((r) => [r.strip, ids.has("tomorrow") ? r.tomorrowStrip : null]));
  const columns = 1 + views.length + (axis ? 1 : 0);
  const n = axis ? (axis.to - axis.from) / 30 : 0;

  return (
    <div class="list">
      <table style={axis ? `--n:${n}` : undefined}>
        <thead>
          <tr>
            <th scope="col">City</th>
            {views.map((v) => (
              <th key={v.id} scope="col" class={`k-${v.id}`}>
                <span>{v.heading}</span>
              </th>
            ))}
            {axis && (
              <th scope="col" class="s">
                <span class="s-today">Today hour by hour, {stripCredit}</span>
                {ids.has("tomorrow") && <span class="s-tomorrow">Tomorrow hour by hour, {stripCredit}</span>}
                <AxisLabels axis={axis} />
              </th>
            )}
          </tr>
        </thead>
        <tbody>
          {rows.map((r, i) => (
            <>
              <tr key={r.location.id} class={r.stale ? "stale" : undefined}>
                <th scope="row">
                  {/* Only link where a city page actually exists; a link to a
                      404 is worse than no link. */}
                  {cityPages ? (
                    <a href={`/${r.location.country}/${r.location.slug}/`}>{r.location.name}</a>
                  ) : (
                    r.location.name
                  )}
                  {r.alert && (
                    <span class="alert" title="EPA has issued a UV Alert for today">
                      UV Alert
                    </span>
                  )}
                </th>
                <NowCell row={r} now={now} measured={measured} />
                {ids.has("peak") && <td class="k-peak"><Value uvi={r.peak} /></td>}
                {ids.has("tomorrow") && <td class="k-tomorrow"><Value uvi={r.tomorrow} /></td>}
                {axis && (
                  <td class="s" aria-hidden="true">
                    {r.strip && <RowStrip strip={r.strip} axis={axis} cls="s-today" />}
                    {ids.has("tomorrow") && r.tomorrowStrip && (
                      <RowStrip strip={r.tomorrowStrip} axis={axis} cls="s-tomorrow" />
                    )}
                  </td>
                )}
              </tr>
              {i === AD_AFTER_ROW - 1 && rows.length > AD_AFTER_ROW && (
                <tr class="ad" aria-hidden="true">
                  <td colspan={columns} />
                </tr>
              )}
            </>
          ))}
        </tbody>
      </table>
    </div>
  );
}

/** "the United States", "the United Kingdom" -- a country's name inside a sentence. */
export function inProse(name: string): string {
  return /^United /.test(name) ? `the ${name}` : name;
}

/**
 * The page title. Where there is no instrument -- the United States -- the page
 * leads with "UV Index Today", because "uv index today" is the single biggest
 * search the research found (over 100k a month in the US) with no small site in
 * its top ten, and this page is the answer to it. Where readings are measured,
 * the country's own name leads: "uv index australia" is the search there.
 */
export function countryTitle(name: string, measured: boolean): string {
  return measured
    ? `UV Index ${name} Today and Tomorrow: Every City`
    : `UV Index Today and Tomorrow in ${inProse(name)}: Every City`;
}

/**
 * The H1: the title's own words in sentence case, less the ": Every City"
 * that only a search result needs. /au/'s said "UV Index Australia" under a
 * title about today and tomorrow, and /us/ repeated itself in an H2.
 */
export function countryHeading(name: string, measured: boolean): string {
  return measured
    ? `UV index ${name} today and tomorrow`
    : `UV index today and tomorrow in ${inProse(name)}`;
}


export function CountryPage(view: CountryView) {
  const { country, rows, now } = view;
  const withReading = rows.filter((r) => r.uvi !== null && !r.stale);
  const highest = withReading.length
    ? withReading.reduce((a, b) => (b.uvi! > a.uvi! ? b : a))
    : null;
  const band = highest ? bandFor(highest.uvi!) : null;
  const views = viewsFor(rows, view.measured);
  // In the US the higher of the EPA's and CAMS's forecast is kept for each
  // hour, so either may have made a cell.
  const stripCredit = view.credit === "epa" ? "forecast by the US EPA and CAMS" : "forecast by CAMS";

  // One page carries both intents rather than splitting them across two thin
  // ones: "uv index <country>" and "uv index tomorrow <country>". The title,
  // the description and the switch all say "tomorrow" on purpose, and the
  // list's heading doubles as the #tomorrow anchor.
  const title = countryTitle(country.name, view.measured);
  const description = view.measured
    ? `Live UV index for ${country.name}, measured by ARPANSA and updated every few ` +
      "minutes, with today's hours and tomorrow's forecast peak for every city. Band and sun " +
      "protection guidance for each station."
    : `UV index forecast for cities across ${inProse(country.name)} today and ` +
      "tomorrow, from the US Environmental Protection Agency and Copernicus. Peak " +
      "level, band and sun protection guidance.";
  const path = `/${country.code}/`;

  const structuredData = [
    {
      "@context": "https://schema.org",
      "@type": "WebPage",
      name: title,
      description,
      url: `${ORIGIN}${path}`,
      inLanguage: "en-AU",
    },
    {
      "@context": "https://schema.org",
      "@type": "BreadcrumbList",
      itemListElement: [
        { "@type": "ListItem", position: 1, name: "Home", item: `${ORIGIN}/` },
        { "@type": "ListItem", position: 2, name: country.name, item: `${ORIGIN}${path}` },
      ],
    },
  ];

  return (
    <Layout
      title={title}
      description={description}
      path={path}
      country={country.code}
      structuredData={structuredData}
    >
      <style dangerouslySetInnerHTML={{ __html: PAGE_CSS + tipRules(rows) + switchRules(views.map((v) => v.id)) }} />

      <h1>{countryHeading(country.name, view.measured)}</h1>

      {/* The one place the band's word is printed: here it changes what to do. */}
      {highest ? (
        <p class="lead">
          {view.measured ? "Highest now: " : "Highest now, forecast: "}
          <strong>
            {view.cityPages ? (
              <a href={`/${highest.location.country}/${highest.location.slug}/`}>{highest.location.name}</a>
            ) : (
              highest.location.name
            )}
          </strong>
          , {formatUvi(highest.uvi!)} {band!.name}. {band!.advice}
        </p>
      ) : (
        <p class="lead">
          {view.measured
            ? "No current readings are available. ARPANSA's stations report every " +
              "few minutes; this page updates with them."
            : `No forecast is available for ${country.name} at the moment. ` +
              "This page updates when the next forecast is published."}
        </p>
      )}

      <div class="daymap">
        {views.length > 1 &&
          views.map((v, i) => (
            <input key={v.id} class="sr" type="radio" name="day" id={`day-${v.id}`} checked={i === 0} />
          ))}
        {/* The H1 already says "today and tomorrow"; this heading says what
            is under it. It keeps the #tomorrow anchor the old URLs 301 to. */}
        <h2 id="tomorrow">Every city</h2>
        {view.cityPages && <CityPicker rows={rows} />}
        {views.length > 1 && (
          <div class="dayswitch">
            {views.map((v) => (
              <label key={v.id} for={`day-${v.id}`}>
                {v.label}
              </label>
            ))}
          </div>
        )}
        <CityList
          rows={rows}
          views={views}
          now={now}
          measured={view.measured}
          cityPages={view.cityPages}
          stripCredit={stripCredit}
        />
        <p class="small muted">
          Ranked by the current level, highest first, then by today's peak.{" "}
          {view.measured
            ? "Times are local to each city."
            : "There is no measured UV source for the United States, so “now” is " +
              "the forecast for the current hour rather than a measurement."}{" "}
          Each strip is a city's daylight hours on its own clock, coloured by band;
          hatching means the forecast does not reach that hour. A dash in place
          of a figure means the forecast does not cover that day.
        </p>
        <CountryMapView
          rows={rows}
          views={views}
          map={view.map}
          countryName={country.name}
          cityPages={view.cityPages}
        />
      </div>

      <p class="small">
        <a href="/uv-index-explained/">What the UV index numbers mean</a>
      </p>

      <div class="credits">
        {view.credit === "arpansa" ? (
          <>
            <p>UV observations courtesy of ARPANSA.</p>
            <p>
              © Commonwealth of Australia as represented by the Australian Radiation
              Protection and Nuclear Safety Agency (ARPANSA).{" "}
              <a href="https://www.arpansa.gov.au/disclaimer" rel="nofollow">
                ARPANSA disclaimer
              </a>
              .
            </p>
          </>
        ) : (
          <p>
            Forecast: US Environmental Protection Agency.{" "}
            <a href="https://www.epa.gov/sunsafety/uv-index-scale-0" rel="nofollow">
              About the EPA UV Index
            </a>
            .
          </p>
        )}
        {view.hasForecast && (
          <p>
            Forecasts contain modified Copernicus Atmosphere Monitoring Service
            information {now.getUTCFullYear()}. Neither the European Commission nor
            ECMWF is responsible for any use of this information.
          </p>
        )}
        <p>Made with Natural Earth.</p>
      </div>
    </Layout>
  );
}
