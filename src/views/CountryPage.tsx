/**
 * City markers, and their hover labels, drawn as two separate layers.
 *
 * They have to be separate. SVG paints in document order and has no working
 * z-index, so a label inside its own marker group is painted *before* every
 * marker that comes after it — and a neighbouring city then covers it. That is
 * exactly what happened: hovering Tampa showed its label with the marker to
 * its right sitting on top of the text.
 *
 * So every marker is drawn first, then every label, and a generated rule per
 * city connects the two. The cost is one CSS rule per city, which compresses
 * to almost nothing because the rules are near-identical.
 */
/**
 * A UV value with its band beside it.
 *
 * Every number carries its own band. A single "Band" column had to describe
 * one of the several numbers in the row, and it described a different one in
 * each country -- UV now in Australia, today's peak in the United States --
 * so the same heading meant two different things depending on the page.
 */
function Uvi({ uvi }: { uvi: number | null }) {
  if (uvi === null) return <span class="muted small">—</span>;
  const band = bandFor(uvi);
  return (
    <span class="uvi">
      <b>{formatUvi(uvi)}</b>
      <span class="band" style={`background:${band.bg};color:${band.fg}`}>{band.name}</span>
    </span>
  );
}

function UviCell({ uvi }: { uvi: number | null }) {
  return (
    <td>
      <Uvi uvi={uvi} />
    </td>
  );
}

/** The map views, in the order they appear on the switch. */
const VIEW_IDS = ["now", "peak", "tomorrow"] as const;
type ViewId = (typeof VIEW_IDS)[number];

/**
 * Show/hide rules for every view, generated rather than written out.
 *
 * Three views give nine combinations, and each has to drive both the SVG
 * marker groups and the caption. Writing those by hand is how the switch came
 * to say "Today" above a map showing the current hour: the label and the
 * layer it controlled were maintained separately.
 */
function switchRules(views: readonly ViewId[]): string {
  let css = "";
  for (const view of views) {
    css +=
      `#day-${view}:checked~.dayswitch label[for="day-${view}"]` +
      `{background:var(--link);color:#fff}`;
    // Focus must show on the label, since the radio itself is off-screen.
    css +=
      `#day-${view}:focus-visible~.dayswitch label[for="day-${view}"]` +
      `{outline:3px solid var(--focus);outline-offset:-3px}`;
    for (const layer of views) {
      const show = layer === view ? "inline" : "none";
      css +=
        `#day-${view}:checked~.mapbox .m-${layer},` +
        `#day-${view}:checked~.daycap .m-${layer}{display:${show}}`;
      // Hover previews a view without committing to it.
      css += `.daymap:has(label[for="day-${view}"]:hover) .m-${layer}{display:${show}}`;
    }
  }
  return css;
}

function MarkerLayer({
  rows,
  map,
  value,
}: {
  rows: readonly CityRow[];
  map: CountryMap;
  value: (r: CityRow) => number | null;
}) {
  return (
    <>
      {rows.map((r) => {
        const uvi = value(r);
        if (uvi === null) return null;
        const { x, y } = map.project(r.location.lat, r.location.lon);
        const band = bandFor(uvi);
        return (
          <g
            key={r.location.id}
            class={`pin p-${r.location.id}`}
            role="img"
            aria-label={`${r.location.name}: UV ${formatUvi(uvi)} ${band.name}`}
          >
            <circle cx={x} cy={y} r="6" fill={band.bg} stroke="var(--bg)" stroke-width="1.5" />
            <text x={x} y={y + 3.2} font-size="7.5" font-weight="700" fill={band.fg}
              text-anchor="middle">{Math.round(uvi)}</text>
          </g>
        );
      })}
    </>
  );
}

function TipLayer({
  rows,
  map,
  value,
}: {
  rows: readonly CityRow[];
  map: CountryMap;
  value: (r: CityRow) => number | null;
}) {
  return (
    <>
      {rows.map((r) => {
        const uvi = value(r);
        if (uvi === null) return null;
        const { x, y } = map.project(r.location.lat, r.location.lon);
        const label = `${r.location.name} ${formatUvi(uvi)}`;
        // SVG cannot size a box to its text, so estimate from character
        // count: generous rather than tight, because slightly too wide looks
        // fine and too narrow clips.
        const width = label.length * 4.6 + 12;
        const flip = y < 26; // near the top edge, put the label below instead
        const ty = flip ? y + 13 : y - 23;
        return (
          <g key={r.location.id} class={`tip t-${r.location.id}`} aria-hidden="true">
            <rect x={x - width / 2} y={ty} width={width} height="15" rx="4"
              fill="var(--fg)" stroke="var(--bg)" stroke-width="0.8" />
            <text x={x} y={ty + 10.5} font-size="8.5" font-weight="600" fill="var(--bg)"
              text-anchor="middle">{label}</text>
          </g>
        );
      })}
    </>
  );
}

/** One rule per city, joining its marker to its label across the two layers. */
function tipRules(rows: readonly CityRow[]): string {
  return rows
    .map((r) => `.daymap:has(.p-${r.location.id}:hover) .t-${r.location.id}{opacity:1}`)
    .join("");
}

function CountryOutline({
  rows,
  map,
  countryName,
  measured,
}: {
  rows: readonly CityRow[];
  map: CountryMap;
  countryName: string;
  measured: boolean;
}) {
  // A view only appears if there is data behind it.
  const views: { id: ViewId; label: string; caption: string; value: (r: CityRow) => number | null }[] =
    [
      {
        id: "now",
        label: measured ? "Now" : "Now (forecast)",
        caption: measured
          ? "Showing the level measured now."
          : "Showing the forecast for the current hour; there is no measured UV source for the United States.",
        value: (r) => r.uvi,
      },
    ];
  if (rows.some((r) => r.peak !== null)) {
    views.push({
      id: "peak",
      label: "Peak today",
      caption: "Showing the highest level forecast for today, in each city's own day.",
      value: (r) => r.peak,
    });
  }
  if (rows.some((r) => r.tomorrow !== null)) {
    views.push({
      id: "tomorrow",
      label: "Tomorrow",
      caption: "Showing the highest level forecast for tomorrow, in each city's own day.",
      value: (r) => r.tomorrow,
    });
  }

  return (
    <div class="daymap">
      <style dangerouslySetInnerHTML={{ __html: switchRules(views.map((v) => v.id)) }} />
      {views.length > 1 && (
        <>
          {views.map((v, i) => (
            <input
              key={v.id}
              class="sr"
              type="radio"
              name="day"
              id={`day-${v.id}`}
              checked={i === 0}
            />
          ))}
          <div class="dayswitch">
            {views.map((v) => (
              <label key={v.id} for={`day-${v.id}`}>
                {v.label}
              </label>
            ))}
          </div>
        </>
      )}
      <div class="mapbox">
        <svg
          viewBox={`0 0 ${map.width} ${map.height}`}
          role="img"
          aria-label={`Map of ${countryName} with a marker for each city. The same figures are listed in the table below.`}
        >
          <path d={map.outlinePath} fill="var(--line)" stroke="var(--muted)" stroke-width="0.8"
            stroke-linejoin="round" opacity="0.75" />
          {/* Markers first, labels second, within each view: SVG paints in
              document order and has no working z-index, so a label nested
              beside its own marker is covered by the next marker along. */}
          {views.map((v) => (
            <g key={v.id} class={`m-${v.id}`}>
              <MarkerLayer rows={rows} map={map} value={v.value} />
              <TipLayer rows={rows} map={map} value={v.value} />
            </g>
          ))}
        </svg>
      </div>
      {views.length > 1 && (
        <p class="daycap">
          {/* The caption is driven by the same generated rules as the markers,
              so the words and the map cannot disagree about what is shown --
              which is exactly what went wrong when a switch labelled "Today"
              sat above a map of the current hour. */}
          {views.map((v) => (
            <span key={v.id} class={`m-${v.id}`}>
              {v.caption}
            </span>
          ))}{" "}
          Every figure is also in the table below.
        </p>
      )}
    </div>
  );
}

export function CountryPage(view: CountryView) {
  const { country, rows, now } = view;
  const withReading = rows.filter((r) => r.uvi !== null && !r.stale);
  const highest = withReading.length
    ? withReading.reduce((a, b) => (b.uvi! > a.uvi! ? b : a))
    : null;
  const band = highest ? bandFor(highest.uvi!) : null;

  // One page carries both intents rather than splitting them across two thin
  // ones: "uv index <country>" and "uv index tomorrow <country>". The title,
  // the description and the table heading below all say "tomorrow" on purpose,
  // and the heading doubles as the #tomorrow anchor.
  const title = view.measured
    ? `UV Index ${country.name} Today and Tomorrow: Every City`
    : `UV Index ${country.name} Today and Tomorrow: Forecast for Every City`;
  const description = view.measured
    ? `Live UV index for ${country.name}, measured by ARPANSA and updated every few ` +
      "minutes, with tomorrow's forecast peak for every city. Band and sun " +
      "protection guidance for each station."
    : `UV index forecast for cities across ${country.name} today and tomorrow, from ` +
      "the US Environmental Protection Agency and Copernicus. Peak level, band and " +
      "sun protection guidance.";
  const path = `/${country.code}/`;

  const structuredData = [
    {
      "@context": "https://schema.org",
      "@type": "WebPage",
      name: title,
      description,
      url: `${ORIGIN}${path}`,
      inLanguage: "en-AU",
    },
    {
      "@context": "https://schema.org",
      "@type": "BreadcrumbList",
      itemListElement: [
        { "@type": "ListItem", position: 1, name: "Home", item: `${ORIGIN}/` },
        { "@type": "ListItem", position: 2, name: country.name, item: `${ORIGIN}${path}` },
      ],
    },
  ];

  return (
    <Layout
      title={title}
      description={description}
      path={path}
      country={country.code}
      structuredData={structuredData}
    >
      <style dangerouslySetInnerHTML={{ __html: PAGE_CSS + tipRules(rows) }} />

      <h1>UV Index {country.name}</h1>

      {highest ? (
        <div class="lead">
          <div class="row">
            <div class="n">{formatUvi(highest.uvi!)}</div>
            <div>
              <p style="margin:0">
                {view.measured ? "Highest now: " : "Highest now, forecast: "}
                {/* Same rule as the table: only link where a city page
                    exists. This one was missed first time round. */}
                <strong>
                  {view.cityPages ? (
                    <a href={`/${highest.location.country}/${highest.location.slug}/`}>
                      {highest.location.name}
                    </a>
                  ) : (
                    highest.location.name
                  )}
                </strong>{" "}
                <span class="band" style={`background:${band!.bg};color:${band!.fg}`}>
                  {band!.name}
                </span>
              </p>
              <p class="small muted" style="margin:4px 0 0">{band!.advice}</p>
            </div>
          </div>
        </div>
      ) : (
        <p>
          {view.measured
            ? "No current readings are available. ARPANSA's stations report every " +
              "few minutes; this page updates with them."
            : `No forecast is available for ${country.name} at the moment. ` +
              "This page updates when the next forecast is published."}
        </p>
      )}

      <CountryOutline
        rows={rows}
        map={view.map}
        countryName={country.name}
        measured={view.measured}
      />

      <h2 id="tomorrow">
        {view.measured
          ? `UV index today and tomorrow in ${country.name}`
          : `UV index today and tomorrow across ${country.name}`}
      </h2>
      <table>
        <thead>
          <tr>
            <th scope="col">City</th>
            <th scope="col">{view.measured ? "UV now" : "Now (forecast)"}</th>
            <th scope="col" class="hide">Peak today</th>
            <th scope="col">Tomorrow</th>
            {view.measured && <th scope="col" class="hide">Measured</th>}
          </tr>
        </thead>
        <tbody>
          {rows.map((r) => (
            <tr key={r.location.id} class={r.stale ? "stale" : undefined}>
              <th scope="row">
                {/* Only link where a city page actually exists; a link to a
                    404 is worse than no link. */}
                {view.cityPages ? (
                  <a href={`/${r.location.country}/${r.location.slug}/`}>{r.location.name}</a>
                ) : (
                  r.location.name
                )}
              </th>
              <UviCell uvi={r.uvi} />
              <td class="hide"><Uvi uvi={r.peak} /></td>
              <td><Uvi uvi={r.tomorrow} /></td>
              {view.measured && (
                <td class="t hide">
                  {r.validAt ? localTimeWithZone(r.validAt, r.location.tz, localeFor(r.location.country)) : "—"}
                  {r.stale ? " (delayed)" : ""}
                </td>
              )}
            </tr>
          ))}
        </tbody>
      </table>
      <p class="small muted">
        Sorted by the current level, highest first, then by today's peak.{" "}
        {view.measured
          ? "Times are local to each city."
          : "There is no measured UV source for the United States, so “now” is " +
            "the forecast for the current hour rather than a measurement."}{" "}
        Every figure carries its own band. Peak figures are the highest the UV index
        reaches in that city’s own day; a dash means the forecast does not cover it.
      </p>

      <p class="small">
        <a href="/uv-index-explained/">What the UV index numbers mean</a>
      </p>

      <div class="credits">
        {view.credit === "arpansa" ? (
          <>
            <p>UV observations courtesy of ARPANSA.</p>
            <p>
              © Commonwealth of Australia as represented by the Australian Radiation
              Protection and Nuclear Safety Agency (ARPANSA).{" "}
              <a href="https://www.arpansa.gov.au/disclaimer" rel="nofollow">
                ARPANSA disclaimer
              </a>
              .
            </p>
          </>
        ) : (
          <p>
            Forecast: US Environmental Protection Agency.{" "}
            <a href="https://www.epa.gov/sunsafety/uv-index-scale-0" rel="nofollow">
              About the EPA UV Index
            </a>
            .
          </p>
        )}
        {view.hasForecast && (
          <p>
            Forecast peaks contain modified Copernicus Atmosphere Monitoring Service
            information {now.getUTCFullYear()}. Neither the European Commission nor
            ECMWF is responsible for any use of this information.
          </p>
        )}
        <p>Made with Natural Earth.</p>
      </div>
    </Layout>
  );
}
